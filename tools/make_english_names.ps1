# Builds the English name table used by F14 (search the crafting and building
# windows by English name while the game is in another language).
#
# Reads the game's English translation files
#   media\lua\shared\Translate\EN\Recipes.json   recipe name   -> English name
#   media\lua\shared\Translate\EN\ItemName.json  item full type -> English name
# and writes mod\...\42\media\lua\client\SurvivorComforts\EnglishNames.lua.
#
# Run it after each game update. It prints how many names were added, removed
# or changed since the last table, with a few examples, and leaves the file as
# it was when nothing changed.
#
#   powershell -File tools\make_english_names.ps1 [-GameDir <game folder>]

param(
    [string]$GameDir = $env:PZ_GAME_DIR
)

$ErrorActionPreference = "Stop"
. (Join-Path $PSScriptRoot "GameDir.ps1")
$GameDir = Resolve-GameDir $GameDir

$translate = Join-Path $GameDir "media\lua\shared\Translate\EN"
$outFile = Join-Path $PSScriptRoot "..\mod\SurvivorComforts\Contents\mods\SurvivorComforts\42\media\lua\client\SurvivorComforts\EnglishNames.lua"
$utf8 = New-Object System.Text.UTF8Encoding $false
$sections = @(
    @{ Name = "recipes"; File = "Recipes.json" },
    @{ Name = "items"; File = "ItemName.json" }
)

# key -> name, from a translation file (a flat JSON object, one "key": "name"
# per line). Read line by line: ConvertFrom-Json treats keys that differ only
# in case as duplicates, and the game's files have some.
function Read-Names($file) {
    $names = New-Object 'System.Collections.Generic.SortedDictionary[string,string]' ([StringComparer]::Ordinal)
    foreach ($line in [IO.File]::ReadAllLines((Join-Path $translate $file), $utf8)) {
        if ($line -match '^\s*"((?:[^"\\]|\\.)*)"\s*:\s*"((?:[^"\\]|\\.)*)"\s*,?\s*$') {
            $key = [regex]::Unescape($Matches[1])
            $name = [regex]::Unescape($Matches[2])
            if ($name.Trim() -ne "") { $names[$key] = $name }
        }
    }
    return ,$names
}

# section -> (key -> name), from the current table, to compare against.
function Read-Table {
    $table = @{}
    if (-not (Test-Path $outFile)) { return $table }
    $section = $null
    foreach ($line in [IO.File]::ReadAllLines($outFile, $utf8)) {
        if ($line -match '^\s*(\w+) = \{$') {
            $section = $Matches[1]
            # Case-sensitive: some keys differ only in case.
            $table[$section] = New-Object 'System.Collections.Generic.Dictionary[string,string]' ([StringComparer]::Ordinal)
        } elseif ($section -and $line -match '^\s*\["((?:[^"\\]|\\.)*)"\] = "((?:[^"\\]|\\.)*)",$') {
            $table[$section][$Matches[1] -replace '\\(.)', '$1'] = $Matches[2] -replace '\\(.)', '$1'
        }
    }
    return $table
}

function Lua-String($s) {
    return '"' + ($s -replace '\\', '\\' -replace '"', '\"' -replace "`r", '' -replace "`n", '\n') + '"'
}

$old = Read-Table
$lines = New-Object System.Collections.Generic.List[string]
$lines.Add("-- English names for F14 (search by English name). Generated by")
$lines.Add("-- tools/make_english_names.ps1 from the game's Translate/EN files; do not edit.")
$lines.Add("SurvivorComforts = SurvivorComforts or {}")
$lines.Add("SurvivorComforts.englishNames = {")
$changed = $false
foreach ($s in $sections) {
    $names = Read-Names $s.File
    $before = if ($old.ContainsKey($s.Name)) { $old[$s.Name] } else { New-Object 'System.Collections.Generic.Dictionary[string,string]' }
    $added = @(); $removed = @(); $renamed = @()
    foreach ($k in $names.Keys) {
        if (-not $before.ContainsKey($k)) { $added += $k }
        elseif ($before[$k] -cne $names[$k]) { $renamed += $k }
    }
    foreach ($k in $before.Keys) { if (-not $names.ContainsKey($k)) { $removed += $k } }
    Write-Host ("{0}: {1} names (added {2}, removed {3}, changed {4})" -f $s.Name, $names.Count, $added.Count, $removed.Count, $renamed.Count)
    foreach ($k in ($added | Select-Object -First 10)) { Write-Host ("  + {0} = {1}" -f $k, $names[$k]) }
    foreach ($k in ($removed | Select-Object -First 10)) { Write-Host ("  - {0}" -f $k) }
    foreach ($k in ($renamed | Select-Object -First 10)) { Write-Host ("  ~ {0}: {1} -> {2}" -f $k, $before[$k], $names[$k]) }
    if ($added.Count + $removed.Count + $renamed.Count -gt 0) { $changed = $true }

    $lines.Add("    $($s.Name) = {")
    foreach ($k in $names.Keys) {
        $lines.Add("        [$(Lua-String $k)] = $(Lua-String $names[$k]),")
    }
    $lines.Add("    },")
}
$lines.Add("}")

if ($changed -or -not (Test-Path $outFile)) {
    [IO.File]::WriteAllText($outFile, ($lines -join "`n") + "`n", $utf8)
    Write-Host "Written $outFile"
} else {
    Write-Host "No changes; $outFile left as it is."
}
